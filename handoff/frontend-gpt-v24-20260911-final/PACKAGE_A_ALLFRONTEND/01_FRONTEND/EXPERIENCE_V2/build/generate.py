# ---------------------------------------------------------------- tree walking
def walk_sections(secs, fn):
    for s in secs or []:
        if not isinstance(s, dict): continue
        fn(s)
        if s.get("type") == "split":
            walk_sections(s.get("main"), fn); walk_sections(s.get("side"), fn)
        elif s.get("type") == "stack":
            walk_sections(s.get("children"), fn)
        elif s.get("type") == "tabs":
            for tb in s.get("tabs", []): walk_sections(tb.get("sections"), fn)

def collect_actions(sid, sp):
    out = []
    def norm(raw, where):
        a = raw or {}
        cls = a.get("cls", "NAVIGATION")
        aid = a.get("id") or ""
        label = a.get("label") or a.get("title") or ""
        is_effect = cls == "EFFECT"
        out.append({
            "action_id": f"{sid}.{aid}" if aid else f"{sid}.{where}",
            "display_label_zh": label,
            "display_key": None,
            "action_class": cls,
            "capability_status": "CODEX_BINDING_REQUIRED" if is_effect or cls == "QUERY" else (
                "VERIFIED_AVAILABLE" if cls == "NAVIGATION" else "PARTIAL"),
            "permission_requirement": a.get("permission", "UNKNOWN"),
            "input_context": {"screen": sid, "section": where, "scope": a.get("scope", "UNKNOWN"),
                              "target": a.get("target", "UNKNOWN")},
            "success_state": "NEEDS_CODEX_DEFINE",
            "failure_state": "NEEDS_CODEX_DEFINE",
            "evidence_effect": "UNKNOWN",
            "binding_owner": "CODEX" if is_effect else "FRONTEND",
            "high_risk_confirmation_required": bool(a.get("risk", False)),
            "prototype_behavior": "confirm-then-toast, never calls backend" if is_effect else "local/navigation only",
            "icon": a.get("ico") or a.get("icon")
        })
    def fn(s):
        t = s.get("type")
        if t == "actions":
            for a in s.get("items", []): norm(a, "actions:" + (s.get("title") or ""))
        if t == "head":
            for a in s.get("actions", []): norm(a, "head")
        if t == "form":
            for a in s.get("actions", []): norm(a, "form:" + (s.get("title") or ""))
        if t == "cards":
            for c in s.get("items", []):
                if c.get("action"): norm(c["action"], "card:" + (c.get("title") or ""))
    walk_sections(sp.get("sections"), fn)
    return out

def collect_copy_keys(sp):
    keys = set([sp["titleKey"]])
    def fn(s):
        for k, v in s.items():
            if k.endswith("Key") and k != "toneKey" and isinstance(v, str) and v: keys.add(v)
    walk_sections(sp.get("sections"), fn)
    return sorted(keys)

