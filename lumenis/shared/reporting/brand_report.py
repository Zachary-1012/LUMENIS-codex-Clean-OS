"""
品牌分析报告生成器（V3.0 P1.4 品牌分析报告升级）
归属：LUMENIS / 序境 · Shared Reporting，服务 BMP / 序境·品牌市场
目标：
  1. 从传统舆情报告升级为品牌传播与市场情报报告
  2. 整合品牌传播分析、市场情报分析、舆情分析、事件关系图谱
  3. 生成结构化、可操作的品牌分析报告

报告结构（V3.0 升级后）：
  1. 执行摘要（Executive Summary）
     - 核心发现
     - 关键指标
     - 行动建议
  2. 品牌传播分析（Brand Communication Analysis）
     - 传播主体分布（官方/KOS/KOL/KOC/普通用户/媒体/机构）
     - 传播渠道分析
     - 传播效果评估（曝光、互动、转化）
     - 内容类型分布
  3. 市场情报分析（Market Intelligence）
     - 竞品动态
     - 行业趋势
     - 市场机会与威胁
  4. 舆情分析（Public Opinion Analysis）
     - 情感分布（正面/负面/中性）
     - 热点话题
     - 关键意见领袖
     - 风险预警
  5. 事件关系图谱（Event Relation Graph）
     - 营销事件
     - 传播事件
     - 舆情事件
     - 事件关系链
  6. 建议与行动方案（Recommendations & Action Plan）
     - 短期行动（1-2周）
     - 中期策略（1-3月）
     - 长期规划（3-12月）

设计原则（V3.0 基线要求）：
  - 数据驱动：所有结论基于真实数据，不编造
  - 结构化：报告结构清晰，便于阅读和决策
  - 可操作：每个分析都有对应的建议和行动方案
  - 可追溯：数据来源可追溯，支持验证
"""
from __future__ import annotations

import json
import os
from datetime import datetime
from typing import Any, Dict, List, Optional


class BrandReportGenerator:
    """品牌分析报告生成器"""

    # 报告三语（序境：中英韩）
    REPORT_LANG_LABELS = {
        'zh': {'title': '品牌传播与市场情报报告', 'dm_title': '问题中心（Decision Information First）',
               'dm_question': '核心问题', 'dm_context': '背景', 'dm_events': '关键事件', 'dm_impacts': '影响',
               'dm_risks': '风险', 'dm_evidence': '证据', 'dm_decisions': '建议',
               'short': '短期（1-2周）', 'medium': '中期（1-3月）', 'long': '长期（3-12月）',
               'footer': '本报告由序境 品牌智能系统自动生成，数据来源可追溯。'},
        'en': {'title': 'Brand Communication & Market Intelligence Report', 'dm_title': 'Problem Center (Decision Information First)',
               'dm_question': 'Core Question', 'dm_context': 'Context', 'dm_events': 'Key Events', 'dm_impacts': 'Impacts',
               'dm_risks': 'Risks', 'dm_evidence': 'Evidence', 'dm_decisions': 'Decisions',
               'short': 'Short-term (1-2w)', 'medium': 'Mid-term (1-3m)', 'long': 'Long-term (3-12m)',
               'footer': 'Generated by LUMENIS Brand & Market (BMP). Sources traceable.'},
        'ko': {'title': '브랜드 커뮤니케이션·시장 정보 보고서', 'dm_title': '문제 중심 (Decision Information First)',
               'dm_question': '핵심 질문', 'dm_context': '배경', 'dm_events': '핵심 이벤트', 'dm_impacts': '영향',
               'dm_risks': '리스크', 'dm_evidence': '근거', 'dm_decisions': '제안',
               'short': '단기 (1-2주)', 'medium': '중기 (1-3개월)', 'long': '장기 (3-12개월)',
               'footer': '序境 브랜드 인텔리전스 시스템 자동 생성. 데이터 출처 추적 가능.'},
    }

    def __init__(self, brand_name: str = '序境', report_period: str = '', language: str = 'zh'):
        self.brand_name = brand_name
        self.report_period = report_period or f"{datetime.now().strftime('%Y年%m月')}"
        self.language = language if language in self.REPORT_LANG_LABELS else 'zh'
        self.report_id = f"BR-{datetime.now().strftime('%Y%m%d-%H%M%S')}"
        self.generated_at = datetime.now().strftime('%Y-%m-%d %H:%M:%S')

        # 报告各部分数据
        # 序境报告母模型（Decision Information First）：问题中心→事件→影响→风险→证据→建议
        self.decision_model = {}
        self.executive_summary = {}
        self.communication_analysis = {}
        self.market_intelligence = {}
        self.public_opinion_analysis = {}
        self.event_graph_analysis = {}
        self.recommendations = {}

    def set_decision_model(self, problem_center: Dict[str, Any],
                            events: List[Dict[str, Any]] = None,
                            impacts: List[Dict[str, Any]] = None,
                            risks: List[Dict[str, Any]] = None,
                            evidence: List[Dict[str, Any]] = None,
                            decisions: Dict[str, List[str]] = None):
        """设置序境报告母模型（Decision Information First：问题中心→事件→影响→风险→证据→建议）

        序境母模型契约见 序境/01-PRODUCT/REPORT_MASTER_MODEL.md。向后兼容 v3.0 结构。
        """
        self.decision_model = {
            'problem_center': problem_center,
            'events': events or [],
            'impacts': impacts or [],
            'risks': risks or [],
            'evidence': evidence or [],
            'decisions': decisions or {'short_term': [], 'medium_term': [], 'long_term': []},
        }

    def set_executive_summary(self, core_findings: List[str], key_metrics: Dict[str, Any],
                               action_items: List[str]):
        """设置执行摘要"""
        self.executive_summary = {
            'core_findings': core_findings,
            'key_metrics': key_metrics,
            'action_items': action_items,
        }

    def set_communication_analysis(self, subject_distribution: Dict[str, int],
                                     channel_analysis: Dict[str, Any],
                                     effect_evaluation: Dict[str, Any],
                                     content_type_distribution: Dict[str, int]):
        """设置品牌传播分析"""
        self.communication_analysis = {
            'subject_distribution': subject_distribution,
            'channel_analysis': channel_analysis,
            'effect_evaluation': effect_evaluation,
            'content_type_distribution': content_type_distribution,
        }

    def set_market_intelligence(self, competitor_updates: List[Dict[str, Any]],
                                  industry_trends: List[str],
                                  opportunities: List[str], threats: List[str]):
        """设置市场情报分析"""
        self.market_intelligence = {
            'competitor_updates': competitor_updates,
            'industry_trends': industry_trends,
            'opportunities': opportunities,
            'threats': threats,
        }

    def set_public_opinion_analysis(self, sentiment_distribution: Dict[str, int],
                                      hot_topics: List[Dict[str, Any]],
                                      key_influencers: List[Dict[str, Any]],
                                      risk_warnings: List[str]):
        """设置舆情分析"""
        self.public_opinion_analysis = {
            'sentiment_distribution': sentiment_distribution,
            'hot_topics': hot_topics,
            'key_influencers': key_influencers,
            'risk_warnings': risk_warnings,
        }

    def set_event_graph_analysis(self, marketing_events: List[Dict[str, Any]],
                                   propagation_events: List[Dict[str, Any]],
                                   opinion_events: List[Dict[str, Any]],
                                   event_chains: List[Dict[str, Any]]):
        """设置事件关系图谱分析"""
        self.event_graph_analysis = {
            'marketing_events': marketing_events,
            'propagation_events': propagation_events,
            'opinion_events': opinion_events,
            'event_chains': event_chains,
        }

    def set_recommendations(self, short_term: List[str], medium_term: List[str],
                             long_term: List[str]):
        """设置建议与行动方案"""
        self.recommendations = {
            'short_term': short_term,
            'medium_term': medium_term,
            'long_term': long_term,
        }

    def generate_report(self) -> Dict[str, Any]:
        """生成完整报告"""
        return {
            'report_id': self.report_id,
            'brand_name': self.brand_name,
            'report_period': self.report_period,
            'generated_at': self.generated_at,
            'report_version': 'v3.0',
            'report_type': '品牌传播与市场情报报告',
            'language': self.language,
            'decision_model': self.decision_model,
            'executive_summary': self.executive_summary,
            'communication_analysis': self.communication_analysis,
            'market_intelligence': self.market_intelligence,
            'public_opinion_analysis': self.public_opinion_analysis,
            'event_graph_analysis': self.event_graph_analysis,
            'recommendations': self.recommendations,
        }

    def export_json(self, filepath: str) -> bool:
        """导出为JSON"""
        try:
            report = self.generate_report()
            with open(filepath, 'w', encoding='utf-8') as f:
                json.dump(report, f, ensure_ascii=False, indent=2)
            return True
        except Exception:
            return False

    def export_markdown(self, filepath: str) -> bool:
        """导出为Markdown"""
        try:
            report = self.generate_report()
            md = self._to_markdown(report)
            with open(filepath, 'w', encoding='utf-8') as f:
                f.write(md)
            return True
        except Exception:
            return False

    def _to_markdown(self, report: Dict[str, Any]) -> str:
        """转换为Markdown格式"""
        lines = []
        lang = self.REPORT_LANG_LABELS.get(report.get('language', 'zh'), self.REPORT_LANG_LABELS['zh'])
        lines.append(f"# {report['brand_name']} {lang['title']}")
        lines.append(f"")
        lines.append(f"- **报告ID**: {report['report_id']}")
        lines.append(f"- **报告周期**: {report['report_period']}")
        lines.append(f"- **生成时间**: {report['generated_at']}")
        lines.append(f"- **报告版本**: {report['report_version']}")
        lines.append(f"")
        lines.append(f"---")
        lines.append(f"")

        # 序境母模型（Decision Information First：首屏决策信息）
        dm = report.get('decision_model', {})
        if dm and dm.get('problem_center'):
            pc = dm['problem_center']
            lines.append(f"## 0. {lang['dm_title']}")
            lines.append(f"")
            if pc.get('question'):
                lines.append(f"**{lang['dm_question']}**：{pc['question']}")
                lines.append(f"")
            if pc.get('context'):
                lines.append(f"**{lang['dm_context']}**：{pc['context']}")
                lines.append(f"")
            if dm.get('events'):
                lines.append(f"### {lang['dm_events']}")
                for ev in dm['events']:
                    lines.append(f"- [{ev.get('date', '')}] **{ev.get('title', '')}**（{ev.get('subject', '')}）：{ev.get('summary', '')}")
                lines.append(f"")
            if dm.get('impacts'):
                lines.append(f"### {lang['dm_impacts']}")
                for imp in dm['impacts']:
                    d = imp.get('direction', '')
                    mark = '▲' if d == 'up' else ('▼' if d == 'down' else '■')
                    lines.append(f"- {mark} **{imp.get('dimension', '')}**：{imp.get('detail', '')}")
                lines.append(f"")
            if dm.get('risks'):
                lines.append(f"### {lang['dm_risks']}")
                for rk in dm['risks']:
                    lv = rk.get('level', '')
                    badge = {'high': '🔴 高', 'medium': '🟠 中', 'low': '🟢 低'}.get(lv, lv)
                    trend = {'rising': '（上升）', 'stable': '（平稳）', 'falling': '（下降）'}.get(rk.get('trend', ''), '')
                    lines.append(f"- {badge} **{rk.get('topic', '')}**{trend}：{rk.get('trigger', '')}")
                lines.append(f"")
            if dm.get('evidence'):
                lines.append(f"### {lang['dm_evidence']}")
                for ev in dm['evidence']:
                    lines.append(f"- [{ev.get('evidence_id', '')}]（{ev.get('kind', '')}）：{ev.get('summary', '')}")
                lines.append(f"")
            if dm.get('decisions'):
                dc = dm['decisions']
                lines.append(f"### {lang['dm_decisions']}")
                if dc.get('short_term'):
                    lines.append(f"{lang['short']}：" + "；".join(dc['short_term']))
                if dc.get('medium_term'):
                    lines.append(f"{lang['medium']}：" + "；".join(dc['medium_term']))
                if dc.get('long_term'):
                    lines.append(f"{lang['long']}：" + "；".join(dc['long_term']))
                lines.append(f"")
            lines.append(f"---")
            lines.append(f"")

        # 执行摘要
        es = report.get('executive_summary', {})
        if es:
            lines.append(f"## 1. 执行摘要")
            lines.append(f"")
            if es.get('core_findings'):
                lines.append(f"### 核心发现")
                for finding in es['core_findings']:
                    lines.append(f"- {finding}")
                lines.append(f"")
            if es.get('key_metrics'):
                lines.append(f"### 关键指标")
                for key, value in es['key_metrics'].items():
                    lines.append(f"- **{key}**: {value}")
                lines.append(f"")
            if es.get('action_items'):
                lines.append(f"### 行动建议")
                for item in es['action_items']:
                    lines.append(f"- {item}")
                lines.append(f"")

        # 品牌传播分析
        ca = report.get('communication_analysis', {})
        if ca:
            lines.append(f"## 2. 品牌传播分析")
            lines.append(f"")
            if ca.get('subject_distribution'):
                lines.append(f"### 传播主体分布")
                for subject, count in ca['subject_distribution'].items():
                    lines.append(f"- {subject}: {count}")
                lines.append(f"")
            if ca.get('effect_evaluation'):
                lines.append(f"### 传播效果评估")
                for key, value in ca['effect_evaluation'].items():
                    lines.append(f"- **{key}**: {value}")
                lines.append(f"")

        # 市场情报分析
        mi = report.get('market_intelligence', {})
        if mi:
            lines.append(f"## 3. 市场情报分析")
            lines.append(f"")
            if mi.get('industry_trends'):
                lines.append(f"### 行业趋势")
                for trend in mi['industry_trends']:
                    lines.append(f"- {trend}")
                lines.append(f"")
            if mi.get('opportunities'):
                lines.append(f"### 市场机会")
                for opp in mi['opportunities']:
                    lines.append(f"- {opp}")
                lines.append(f"")
            if mi.get('threats'):
                lines.append(f"### 市场威胁")
                for threat in mi['threats']:
                    lines.append(f"- {threat}")
                lines.append(f"")

        # 舆情分析
        po = report.get('public_opinion_analysis', {})
        if po:
            lines.append(f"## 4. 舆情分析")
            lines.append(f"")
            if po.get('sentiment_distribution'):
                lines.append(f"### 情感分布")
                for sentiment, count in po['sentiment_distribution'].items():
                    lines.append(f"- {sentiment}: {count}")
                lines.append(f"")
            if po.get('risk_warnings'):
                lines.append(f"### 风险预警")
                for warning in po['risk_warnings']:
                    lines.append(f"- ⚠️ {warning}")
                lines.append(f"")

        # 事件关系图谱
        eg = report.get('event_graph_analysis', {})
        if eg:
            lines.append(f"## 5. 事件关系图谱")
            lines.append(f"")
            if eg.get('marketing_events'):
                lines.append(f"### 营销事件")
                for event in eg['marketing_events']:
                    lines.append(f"- **{event.get('title', '')}**: {event.get('description', '')}")
                lines.append(f"")
            if eg.get('event_chains'):
                lines.append(f"### 事件关系链")
                for chain in eg['event_chains']:
                    lines.append(f"- {chain.get('description', '')}")
                lines.append(f"")

        # 建议与行动方案
        rec = report.get('recommendations', {})
        if rec:
            lines.append(f"## 6. 建议与行动方案")
            lines.append(f"")
            if rec.get('short_term'):
                lines.append(f"### 短期行动（1-2周）")
                for item in rec['short_term']:
                    lines.append(f"- {item}")
                lines.append(f"")
            if rec.get('medium_term'):
                lines.append(f"### 中期策略（1-3月）")
                for item in rec['medium_term']:
                    lines.append(f"- {item}")
                lines.append(f"")
            if rec.get('long_term'):
                lines.append(f"### 长期规划（3-12月）")
                for item in rec['long_term']:
                    lines.append(f"- {item}")
                lines.append(f"")

        lines.append(f"---")
        lines.append(f"*{lang['footer']}*")

        return '\n'.join(lines)


# 全局单例
_generator_instance: Optional[BrandReportGenerator] = None

def get_report_generator(brand_name: str = '序境', report_period: str = '') -> BrandReportGenerator:
    global _generator_instance
    if _generator_instance is None:
        _generator_instance = BrandReportGenerator(brand_name, report_period)
    return _generator_instance