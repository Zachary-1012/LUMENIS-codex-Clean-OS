"""Generate inventory only. It does not convert module counts into acceptance."""
from pathlib import Path
import datetime, hashlib, json, re, os
root=Path(__file__).resolve().parents[1]
base=Path(os.environ.get('LUMENIS_RECOVERED_SOURCE_ROOT',root.parent/'recovery_inspection_20261017/site_source_readback/dist'))
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
entries=[]
for p in sorted((root/'src').glob('*.mjs')):
    text=p.read_text()
    for m in re.finditer(r"\[\s*'([^']+)'\s*,\s*'(\d{2,3})'\s*,\s*'[^']*'\s*,\s*'([^']*)'",text):
        entries.append(dict(id=m[1],original_number=int(m[2]),title=m[3],declaration_file=str(p.relative_to(root)),line=text[:m.start()].count('\n')+1,browser='PENDING',backend='UNBOUND'))
entries.sort(key=lambda e:e['original_number'])
(root/'src/study-source.mjs').write_text('// Generated by tools/index_evidence.py from actual study declarations.\nexport const STUDY_SOURCE=Object.freeze('+json.dumps({e['id']:e['declaration_file'] for e in entries},ensure_ascii=False,sort_keys=True)+');\n')
assert len({e['id'] for e in entries})==len(entries)
modules=[]
for p in sorted((root/'src').glob('*.mjs')):
    modules.append(dict(module=p.name,direct_test_imports=[str(t.relative_to(root)) for t in sorted((root/'tests').glob('*.test.mjs')) if '../src/'+p.name in t.read_text()]))
log=(root/'evidence/current-regression.log').read_text()
counts=re.findall(r'ℹ pass (\d+)',log)
fail_counts=re.findall(r'ℹ fail (\d+)',log)
skip_counts=re.findall(r'ℹ skipped (\d+)',log)
regression={'pass':int(counts[-1]) if counts else None,'fail':int(fail_counts[-1]) if fail_counts else None,'skipped':int(skip_counts[-1]) if skip_counts else None}
regression['all_passed']=regression['fail']==0 and regression['pass'] is not None
result=dict(generated_at=datetime.datetime.now(datetime.timezone.utc).isoformat(),status='entry/module inventory, NOT semantic 200+ requirement coverage',entries=entries,entry_count=len(entries),original_numbers='01–39 and69 recovered/corrected;70–73 NEW source-backed implementations;40–68 NOT restored',full_regression_checkpoint=regression['pass'] if regression['all_passed'] else None,regression=regression,modules=modules,direct_import_is_not_complete_behavior_coverage=True)
(root/'evidence/ENTRY_AND_TEST_INDEX.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
changes=[]
for p in sorted((root/'src').iterdir()):
    if not p.is_file():continue
    old=base/'src'/p.name
    if not old.exists() or sha(old)!=sha(p):changes.append(dict(path=str(p.relative_to(root)),recovered_sha256=sha(old) if old.exists() else None,working_sha256=sha(p)))
(root/'evidence/SOURCE_DELTA.json').write_text(json.dumps(dict(base='v12 eb60b7a',baseline_available=base.is_dir(),comparison_status='HASH_COMPARED' if base.is_dir() else 'BASELINE_UNAVAILABLE_NOT_A_RECOVERY_CLAIM',changes=changes),indent=2)+'\n')
print(f'{len(entries)} entries, {len(modules)} modules, last log pass={result["full_regression_checkpoint"]}')
